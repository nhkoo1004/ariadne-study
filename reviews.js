(() => {
  const grid = document.getElementById('review-grid');
  if (!grid) return;
  const el = (tag, cls, text) => {
    const node = document.createElement(tag);
    if (cls) node.className = cls;
    if (text) node.textContent = text;
    return node;
  };
  REVIEWS.forEach(r => {
    const card = el('article', 'review ' + (r.part === '취준생' ? 'career' : 'student'));
    const head = el('div', 'review-head');
    head.append(el('span', 'review-part', r.part + ' 파트'), el('span', 'review-title', r.title));
    const quote = el('p', 'review-quote', r.quote);
    const body = el('p', 'review-body', r.body);
    const who = el('p', 'review-who', '— ' + r.who);
    card.append(head, quote, body, who);
    grid.append(card);
  });
})();
